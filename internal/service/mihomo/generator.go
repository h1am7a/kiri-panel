package mihomo

import (
	"fmt"
	"strings"
)

// AWGProxyOptions defines configuration for the AmneziaWG proxy in Mihomo.
type AWGProxyOptions struct {
	Name         string `json:"name"`
	Server       string `json:"server"`
	Port         int    `json:"port"`
	ClientIP     string `json:"client_ip"`
	ServerPubKey string `json:"server_public_key"`
	ClientPrivKey string `json:"client_private_key"`
	MTU          int    `json:"mtu"`
	Jc           int    `json:"jc"`
	Jmin         int    `json:"jmin"`
	Jmax         int    `json:"jmax"`
	S1           int    `json:"s1"`
	S2           int    `json:"s2"`
	H1           uint32 `json:"h1"`
	H2           uint32 `json:"h2"`
	H3           uint32 `json:"h3"`
	H4           uint32 `json:"h4"`
}

// Hy2ProxyOptions defines configuration for the Hysteria 2 proxy in Mihomo.
type Hy2ProxyOptions struct {
	Name         string `json:"name"`
	Server       string `json:"server"`
	Port         int    `json:"port"`
	Ports        string `json:"ports"` // Port-hopping range, e.g. "20000-50000"
	Password     string `json:"password"`
	ObfsType     string `json:"obfs_type"` // Defaults to "gecko"
	ObfsPassword string `json:"obfs_password"`
	SNI          string `json:"sni"`
	Insecure     bool   `json:"insecure"`
}

// SubscriptionOptions parameters for building a complete Mihomo / Clash.Meta profile.
type SubscriptionOptions struct {
	GroupName string          `json:"group_name"` // Defaults to "Семейный VPN"
	AWG       AWGProxyOptions `json:"awg"`
	Hy2       Hy2ProxyOptions `json:"hy2"`
}

// GenerateConfig generates a complete production-grade Mihomo YAML subscription config.
func GenerateConfig(opts SubscriptionOptions) string {
	groupName := opts.GroupName
	if groupName == "" {
		groupName = "Семейный VPN"
	}

	awgName := opts.AWG.Name
	if awgName == "" {
		awgName = "AmneziaWG"
	}

	hy2Name := opts.Hy2.Name
	if hy2Name == "" {
		hy2Name = "Hysteria 2"
	}

	mtu := opts.AWG.MTU
	if mtu <= 0 {
		mtu = 1280
	}

	obfsType := opts.Hy2.ObfsType
	if obfsType == "" {
		obfsType = "gecko"
	}

	var sb strings.Builder

	// Header and General Settings
	sb.WriteString("# Mihomo (Clash.Meta) Configuration generated by Kiri Panel\n")
	sb.WriteString("mixed-port: 7890\n")
	sb.WriteString("allow-lan: false\n")
	sb.WriteString("mode: rule\n")
	sb.WriteString("log-level: info\n")
	sb.WriteString("ipv6: false\n")
	sb.WriteString("find-process-mode: strict\n\n")

	// TUN Settings
	sb.WriteString("tun:\n")
	sb.WriteString("  enable: true\n")
	sb.WriteString("  stack: mixed\n")
	sb.WriteString("  auto-route: true\n")
	sb.WriteString("  auto-detect-interface: true\n")
	sb.WriteString("  dns-hijack:\n")
	sb.WriteString("    - tcp://any:53\n")
	sb.WriteString("    - udp://any:53\n\n")

	// DNS Settings
	sb.WriteString("dns:\n")
	sb.WriteString("  enable: true\n")
	sb.WriteString("  listen: 0.0.0.0:1053\n")
	sb.WriteString("  ipv6: false\n")
	sb.WriteString("  enhanced-mode: fake-ip\n")
	sb.WriteString("  fake-ip-range: 198.18.0.1/16\n")
	sb.WriteString("  fake-ip-filter:\n")
	sb.WriteString("    - \"*.lan\"\n")
	sb.WriteString("    - \"*.local\"\n")
	sb.WriteString("  nameserver:\n")
	sb.WriteString("    - 1.1.1.1\n")
	sb.WriteString("    - 8.8.8.8\n")
	sb.WriteString("  fallback:\n")
	sb.WriteString("    - 77.88.8.8\n\n")

	// Proxies
	sb.WriteString("proxies:\n")

	// 1. AmneziaWG Proxy
	sb.WriteString(fmt.Sprintf("  - name: %q\n", awgName))
	sb.WriteString("    type: wireguard\n")
	sb.WriteString(fmt.Sprintf("    server: %s\n", opts.AWG.Server))
	sb.WriteString(fmt.Sprintf("    port: %d\n", opts.AWG.Port))
	sb.WriteString(fmt.Sprintf("    ip: %s\n", opts.AWG.ClientIP))
	sb.WriteString(fmt.Sprintf("    public-key: %q\n", opts.AWG.ServerPubKey))
	sb.WriteString(fmt.Sprintf("    private-key: %q\n", opts.AWG.ClientPrivKey))
	sb.WriteString("    udp: true\n")
	sb.WriteString(fmt.Sprintf("    mtu: %d\n", mtu))
	sb.WriteString("    remote-dns-resolve: true\n")
	sb.WriteString("    amnezia-wg-option:\n")
	sb.WriteString(fmt.Sprintf("      jc: %d\n", opts.AWG.Jc))
	sb.WriteString(fmt.Sprintf("      jmin: %d\n", opts.AWG.Jmin))
	sb.WriteString(fmt.Sprintf("      jmax: %d\n", opts.AWG.Jmax))
	sb.WriteString(fmt.Sprintf("      s1: %d\n", opts.AWG.S1))
	sb.WriteString(fmt.Sprintf("      s2: %d\n", opts.AWG.S2))
	sb.WriteString(fmt.Sprintf("      h1: %d\n", opts.AWG.H1))
	sb.WriteString(fmt.Sprintf("      h2: %d\n", opts.AWG.H2))
	sb.WriteString(fmt.Sprintf("      h3: %d\n", opts.AWG.H3))
	sb.WriteString(fmt.Sprintf("      h4: %d\n\n", opts.AWG.H4))

	// 2. Hysteria 2 Proxy
	sb.WriteString(fmt.Sprintf("  - name: %q\n", hy2Name))
	sb.WriteString("    type: hysteria2\n")
	sb.WriteString(fmt.Sprintf("    server: %s\n", opts.Hy2.Server))
	sb.WriteString(fmt.Sprintf("    port: %d\n", opts.Hy2.Port))
	if opts.Hy2.Ports != "" {
		sb.WriteString(fmt.Sprintf("    ports: %s\n", opts.Hy2.Ports))
	}
	sb.WriteString(fmt.Sprintf("    password: %q\n", opts.Hy2.Password))
	if opts.Hy2.SNI != "" {
		sb.WriteString(fmt.Sprintf("    sni: %s\n", opts.Hy2.SNI))
	}
	if opts.Hy2.Insecure {
		sb.WriteString("    skip-cert-verify: true\n")
	} else {
		sb.WriteString("    skip-cert-verify: false\n")
	}
	if opts.Hy2.ObfsPassword != "" {
		sb.WriteString(fmt.Sprintf("    obfs: %s\n", obfsType))
		sb.WriteString(fmt.Sprintf("    obfs-password: %q\n", opts.Hy2.ObfsPassword))
	}
	sb.WriteString("\n")

	// Proxy Groups: Fallback (AmneziaWG primary, Hysteria 2 backup)
	sb.WriteString("proxy-groups:\n")
	sb.WriteString(fmt.Sprintf("  - name: %q\n", groupName))
	sb.WriteString("    type: fallback\n")
	sb.WriteString("    url: https://www.gstatic.com/generate_204\n")
	sb.WriteString("    interval: 300\n")
	sb.WriteString("    timeout: 3000\n")
	sb.WriteString("    lazy: false\n")
	sb.WriteString("    proxies:\n")
	sb.WriteString(fmt.Sprintf("      - %q\n", awgName))
	sb.WriteString(fmt.Sprintf("      - %q\n\n", hy2Name))

	// Routing Rules (Split tunneling)
	sb.WriteString("rules:\n")
	sb.WriteString("  - GEOSITE,category-gov-ru,DIRECT\n")
	sb.WriteString("  - GEOSITE,category-banking-ru,DIRECT\n")
	sb.WriteString("  - GEOSITE,ru,DIRECT\n")
	sb.WriteString("  - GEOIP,RU,DIRECT,no-resolve\n")
	sb.WriteString(fmt.Sprintf("  - MATCH,%s\n", groupName))

	return sb.String()
}
